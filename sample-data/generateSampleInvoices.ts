import { createCanvas } from '@napi-rs/canvas';
import fs from 'fs';
import path from 'path';
import PDFDocument from 'pdfkit';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const outDir = path.resolve(__dirname, 'invoices');

interface SampleInvoiceSpec {
  filename: string;
  invoiceNumber: string;
  invoiceDate: string;
  poReference: string;
  irn: string;
  supplierName: string;
  supplierGstin: string;
  supplierAddress: string;
  bankIdentifier: string;
  buyerName: string;
  buyerGstin: string;
  lines: Array<{
    description: string;
    hsn: string;
    quantity: number;
    unit: string;
    unitPrice: number;
    amount: number;
  }>;
  subtotal: number;
  cgst: number;
  sgst: number;
  igst: number;
  total: number;
}

function writeCleanPdf(spec: SampleInvoiceSpec): Promise<void> {
  return new Promise((resolve, reject) => {
    const filePath = path.join(outDir, spec.filename);
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);

    doc.fontSize(9).fillColor('#92400E').text('SAMPLE DATA - FOR DEMONSTRATION ONLY (ABC MANUFACTURING DEMO)', { align: 'center' });
    doc.moveDown(0.5);

    doc.fontSize(18).fillColor('#0F172A').text('TAX INVOICE', { align: 'left' });
    doc.fontSize(10).fillColor('#475569').text(spec.supplierName);
    doc.text(`GSTIN: ${spec.supplierGstin}`);
    doc.text(spec.supplierAddress);
    doc.text(`Bank Identifier: ${spec.bankIdentifier}`);
    doc.moveDown(1);

    doc.fillColor('#0F172A').fontSize(10);
    doc.text(`Invoice Number: ${spec.invoiceNumber}`);
    doc.text(`Invoice Date: ${spec.invoiceDate}`);
    doc.text(`PO Reference: ${spec.poReference}`);
    doc.text(`IRN: ${spec.irn}`);
    doc.moveDown(0.8);

    doc.fontSize(10).fillColor('#0F172A').text(`Bill To: ${spec.buyerName}`);
    doc.fillColor('#475569').text(`Buyer GSTIN: ${spec.buyerGstin}`);
    doc.moveDown(1);

    doc.fillColor('#0F172A').fontSize(10).text('Line Items:', { underline: true });
    doc.moveDown(0.4);

    spec.lines.forEach((line, idx) => {
      doc.text(
        `${idx + 1}. ${line.description} | HSN: ${line.hsn} | Qty: ${line.quantity} ${line.unit} | Rate: Rs ${line.unitPrice.toFixed(2)} | Amount: Rs ${line.amount.toFixed(2)}`
      );
      doc.moveDown(0.3);
    });

    doc.moveDown(0.8);
    doc.text(`Subtotal: Rs ${spec.subtotal.toFixed(2)}`);
    doc.text(`CGST (9%): Rs ${spec.cgst.toFixed(2)}`);
    doc.text(`SGST (9%): Rs ${spec.sgst.toFixed(2)}`);
    doc.text(`IGST (0%): Rs ${spec.igst.toFixed(2)}`);
    doc.fontSize(12).text(`Total Amount: Rs ${spec.total.toFixed(2)}`);

    doc.moveDown(1.5);
    doc.fontSize(8).fillColor('#64748B').text('Sample Data Document generated by FINSHIELD AI Phase 3.');

    doc.end();
    stream.on('finish', resolve);
    stream.on('error', reject);
  });
}

function writeLowQualityScannedPdf(spec: SampleInvoiceSpec): Promise<void> {
  return new Promise((resolve, reject) => {
    const width = 1240;
    const height = 1754;
    const canvas = createCanvas(width, height);
    const ctx = canvas.getContext('2d');

    // Aged scanned paper background
    ctx.fillStyle = '#EAE6DC';
    ctx.fillRect(0, 0, width, height);

    // Slight scanner skew
    ctx.save();
    ctx.translate(width / 2, height / 2);
    ctx.rotate((1.3 * Math.PI) / 180);
    ctx.translate(-width / 2, -height / 2);

    ctx.fillStyle = '#3B3A36';
    ctx.font = 'bold 20px sans-serif';
    ctx.fillText('SAMPLE DATA - SCANNED INVOICE COPY (LOW QUALITY DEMO)', 80, 90);

    ctx.font = 'bold 34px sans-serif';
    ctx.fillText('TAX INVOICE', 80, 160);

    ctx.font = '24px sans-serif';
    ctx.fillText(spec.supplierName, 80, 220);
    // Faint/low-contrast GSTIN and PO reference to create genuine low OCR confidence
    ctx.fillStyle = '#A8A39A';
    ctx.fillText(`GSTIN: ${spec.supplierGstin}`, 80, 260);
    ctx.fillStyle = '#3B3A36';
    ctx.fillText(spec.supplierAddress, 80, 300);
    ctx.fillText(`Bank Identifier: ${spec.bankIdentifier}`, 80, 340);

    ctx.fillText(`Invoice Number: ${spec.invoiceNumber}`, 80, 420);
    ctx.fillText(`Invoice Date: ${spec.invoiceDate}`, 80, 460);
    ctx.fillStyle = '#B8B3AA';
    ctx.fillText(`PO Reference: ${spec.poReference}`, 80, 500);
    ctx.fillStyle = 'rgba(234,230,220,0.55)';
    ctx.fillRect(230, 475, 190, 32);
    ctx.fillStyle = '#3B3A36';
    ctx.fillText(`Bill To: ${spec.buyerName} (${spec.buyerGstin})`, 80, 560);

    ctx.fillText('Description | Qty | Unit Price | Amount', 80, 650);
    ctx.strokeStyle = '#6E6B64';
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(80, 665);
    ctx.lineTo(1140, 665);
    ctx.stroke();

    let y = 710;
    spec.lines.forEach((line, idx) => {
      ctx.fillStyle = '#3B3A36';
      ctx.fillText(
        `${idx + 1}. ${line.description} | ${line.quantity} ${line.unit} | Rs ${line.unitPrice.toFixed(2)} | Rs ${line.amount.toFixed(2)}`,
        80,
        y
      );
      y += 50;
    });

    y += 40;
    ctx.fillText(`Subtotal: Rs ${spec.subtotal.toFixed(2)}`, 80, y);
    ctx.fillText(`CGST (9%): Rs ${spec.cgst.toFixed(2)}`, 80, y + 45);
    ctx.fillText(`SGST (9%): Rs ${spec.sgst.toFixed(2)}`, 80, y + 90);
    ctx.fillStyle = '#7C7870';
    ctx.font = 'bold 28px sans-serif';
    ctx.fillText(`Total Amount: Rs ${spec.total.toFixed(2)}`, 80, y + 145);

    ctx.restore();

    // Add realistic scanner speckle noise & horizontal scan artifact lines
    for (let i = 0; i < 4500; i++) {
      const nx = Math.floor(Math.random() * width);
      const ny = Math.floor(Math.random() * height);
      ctx.fillStyle = i % 2 === 0 ? 'rgba(40,40,40,0.22)' : 'rgba(255,255,255,0.25)';
      ctx.fillRect(nx, ny, 2, 2);
    }
    for (let s = 0; s < 14; s++) {
      const sy = 150 + s * 105;
      ctx.fillStyle = 'rgba(80,75,70,0.12)';
      ctx.fillRect(40, sy, width - 80, 2);
    }

    const jpegBuffer = canvas.toBuffer('image/jpeg', 42);

    const filePath = path.join(outDir, spec.filename);
    const doc = new PDFDocument({ size: [width, height], margin: 0 });
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);
    doc.image(jpegBuffer, 0, 0, { width, height });
    doc.end();
    stream.on('finish', resolve);
    stream.on('error', reject);
  });
}

